interface I18nContextType {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: string) => string
}

const I18nContext = createContext<I18nContextType>({
  locale: 'en',
  setLocale: () => {},
  t: (key) => key,
})

const LOCALE_KEY = 'xylon-locale'
const LOCALE_CHANGE_EVENT = 'xylon-locale-change'
let volatileLocale: Locale | null = null

function browserLocale(): Locale {
  if (volatileLocale) return volatileLocale
  try {
    const saved = localStorage.getItem(LOCALE_KEY)
    if (saved === 'en' || saved === 'zh-TW') return saved
  } catch {
    // Keep the language switch usable when browser storage is unavailable.
  }
  return navigator.language.startsWith('zh') ? 'zh-TW' : 'en'
}

function subscribeLocale(notify: () => void): () => void {
  const handleStorage = () => {
    volatileLocale = null
    notify()
  }
  window.addEventListener('storage', handleStorage)
  window.addEventListener(LOCALE_CHANGE_EVENT, notify)
  return () => {
    window.removeEventListener('storage', handleStorage)
    window.removeEventListener(LOCALE_CHANGE_EVENT, notify)
  }
}

function serverLocale(): Locale {
  return 'en'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const locale = useSyncExternalStore(subscribeLocale, browserLocale, serverLocale)

  useEffect(() => {
    document.documentElement.lang = locale
  }, [locale])

  const setLocale = useCallback((l: Locale) => {
    volatileLocale = l
    try {
      localStorage.setItem(LOCALE_KEY, l)
    } catch {
      // The in-memory value still updates the current page.
    }
    window.dispatchEvent(new Event(LOCALE_CHANGE_EVENT))
  }, [])

  const t = useCallback((key: string): string => {
    return translations[locale][key] || translations['en'][key] || key
  }, [locale])

  return (
    <I18nContext.Provider value={{ locale, setLocale, t }}>
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n() {
  return useContext(I18nContext)
}
